    fun generateCandlesForAsset(asset: AssetUniverseItem, count: Int = 26): List<Candle> {
        val series = mutableListOf<Candle>()
        var price = asset.prevClose
        val totalChange = asset.price - asset.prevClose
        val driftPerStep = totalChange / count
        val volatility = maxOf(1.0, asset.price * 0.002)

        var ema = price
        val k = 2.0 / (10.0 + 1.0)

        for (i in 0 until count) {
            val open = price
            val isLast = (i == count - 1)
            val targetClose = if (isLast) asset.price else (open + driftPerStep + sin(i * 0.8) * volatility)
            val high = maxOf(open, targetClose) + abs(cos(i * 1.1)) * volatility
            val low = minOf(open, targetClose) - abs(sin(i * 1.3)) * volatility
            val close = if (isLast) asset.price else targetClose
            val vol = (30000 + abs(sin(i.toDouble())) * 90000).toLong()

            ema = (close * k) + (ema * (1.0 - k))

            val m = 9 * 60 + 15 + i * 15
            val hh = (m / 60).toString().padStart(2, '0')
            val mm = (m % 60).toString().padStart(2, '0')

            series.add(
                Candle(
                    time = "$hh:$mm",
                    open = (open * 100).roundToInt() / 100.0,
                    high = (high * 100).roundToInt() / 100.0,
                    low = (low * 100).roundToInt() / 100.0,
                    close = (close * 100).roundToInt() / 100.0,
                    volume = vol,
                    ema = (ema * 100).roundToInt() / 100.0
                )
            )
            price = close
        }
        return series
    }
